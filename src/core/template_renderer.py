# -*- coding: utf-8 -*-
import json
from dataclasses import dataclass
from datetime import date, datetime

from liquid import Environment, Mode


class TemplateRenderError(Exception):
    """模板解析或渲染失败时抛出的人类可读错误。"""


@dataclass
class TemplateInputField:
    key: str
    label: str
    default: str = ""


@dataclass
class PreparedTemplate:
    original_text: str
    parts: tuple
    input_fields: list
    uses_clipboard: bool = False


class TemplateRenderer:
    """将 QuickKV 的中文模板语法解析为可执行的安全模板。"""

    MAX_EXPRESSIONS = 4096
    MAX_EXPRESSION_LENGTH = 64 * 1024
    MAX_DYNAMIC_OUTPUT = 16 * 1024 * 1024
    SUPPORTED_VARIABLES = {"今天", "现在", "剪贴板"}
    SUPPORTED_FILTERS = {"默认", "格式化", "大写", "小写", "去空格"}

    def __init__(self):
        self.environment = Environment(
            tolerance=Mode.STRICT,
            strict_filters=True,
            autoescape=False,
        )
        self.environment.tags = {name: self.environment.tags[name] for name in ("content", "output", "illegal")}
        self.environment.filters.clear()
        self.environment.output_stream_limit = self.MAX_DYNAMIC_OUTPUT
        self.environment.add_filter("默认", self._filter_default)
        self.environment.add_filter("格式化", self._filter_format)
        self.environment.add_filter("大写", self._filter_upper)
        self.environment.add_filter("小写", self._filter_lower)
        self.environment.add_filter("去空格", self._filter_trim)

    def contains_template(self, text):
        return bool(text) and "{{" in text and "}}" in text

    def prepare(self, text):
        if not self.contains_template(text):
            return PreparedTemplate(text, (text,), [])

        parts = []
        compiled = {}
        input_registry = {}
        uses_clipboard = False
        cursor = 0
        count = 0
        while (start := text.find("{{", cursor)) != -1:
            end = text.find("}}", start + 2)
            if end == -1:
                break
            count += 1
            if count > self.MAX_EXPRESSIONS:
                raise TemplateRenderError("模板表达式过多，本次输出已取消。")
            if end - start - 2 > self.MAX_EXPRESSION_LENGTH:
                raise TemplateRenderError("单个模板表达式过长，本次输出已取消。")
            parts.append(text[cursor:start])
            expression = text[start + 2:end].strip()
            try:
                if expression not in compiled:
                    arguments = {}
                    source = self._transform_expression(expression, input_registry, arguments)
                    # Only identifiers and filters generated by the parser enter Liquid.
                    compiled[expression] = (self.environment.from_string("{{ " + source + " }}"), arguments)
                    uses_clipboard |= source.split(" | ", 1)[0] == "clipboard"
                parts.append(compiled[expression])
            except TemplateRenderError:
                raise
            except Exception:
                raise TemplateRenderError("模板语法错误，请检查变量及过滤器。") from None
            cursor = end + 2
        if not cursor:
            raise TemplateRenderError("模板语法不完整，请检查 {{ 和 }} 是否成对出现。")
        parts.append(text[cursor:])
        return PreparedTemplate(text, tuple(parts), list(input_registry.values()), uses_clipboard)

    def render(self, prepared_template, input_values=None, clipboard_text=""):
        if len(prepared_template.parts) == 1:
            return prepared_template.parts[0]
        input_values = input_values or {}
        today = date.today()
        now = datetime.now()
        context = {
            "today_text": today.isoformat(), "today_value": today,
            "now_text": now.strftime("%Y-%m-%d %H:%M"), "now_value": now,
        }
        if prepared_template.uses_clipboard:
            context["clipboard"] = clipboard_text or ""
        for field in prepared_template.input_fields:
            context[field.key] = input_values.get(field.key, "")

        rendered = []
        dynamic_size = 0
        try:
            for part in prepared_template.parts:
                if isinstance(part, str):
                    rendered.append(part)
                    continue
                template, arguments = part
                output = template.render(**context, **arguments)
                dynamic_size += len(output.encode("utf-8"))
                if dynamic_size > self.MAX_DYNAMIC_OUTPUT:
                    raise TemplateRenderError("模板动态输出过长，本次输出已取消。")
                rendered.append(output)
        except TemplateRenderError:
            raise
        except Exception:
            raise TemplateRenderError("模板渲染失败，请检查过滤器参数或输出长度。") from None
        return "".join(rendered)

    def _transform_expression(self, expression, input_registry, arguments):
        raw_segments = expression.split("|")
        if any(not segment.strip() for segment in raw_segments):
            raise TemplateRenderError("模板表达式写法不正确，请检查过滤器分隔符。")

        segments = [segment.strip() for segment in raw_segments]
        base_kind, internal_base, field = self._parse_base_segment(segments[0], input_registry)

        has_format_filter = False
        transformed_filters = []

        for filter_segment in segments[1:]:
            filter_name, filter_arg = self._parse_filter_segment(filter_segment)
            if filter_name not in self.SUPPORTED_FILTERS:
                raise TemplateRenderError("未识别模板过滤器。")

            if filter_name == "格式化":
                if base_kind not in {"today", "now"}:
                    raise TemplateRenderError("“格式化”只能用于 {{今天}} 或 {{现在}}。")
                has_format_filter = True
                if not filter_arg:
                    raise TemplateRenderError("“格式化”缺少格式内容。")
            elif filter_name == "默认":
                if not filter_arg:
                    raise TemplateRenderError("“默认”缺少默认值。")
                if field and not field.default:
                    field.default = filter_arg
            elif filter_arg:
                raise TemplateRenderError(f"过滤器“{filter_name}”不接受额外参数。")

            if filter_arg is None:
                transformed_filters.append(filter_name)
            else:
                key = f"argument_{len(arguments)}"
                # Keep the escaped spelling formerly returned by Liquid string literals.
                arguments[key] = json.dumps(filter_arg, ensure_ascii=False)[1:-1].replace(chr(92) + '"', '"')
                transformed_filters.append(f"{filter_name}: {key}")

        if base_kind == "today":
            internal_base = "today_value" if has_format_filter else "today_text"
        elif base_kind == "now":
            internal_base = "now_value" if has_format_filter else "now_text"

        if not transformed_filters:
            return internal_base
        return " | ".join([internal_base] + transformed_filters)

    def _parse_base_segment(self, base_segment, input_registry):
        if base_segment in self.SUPPORTED_VARIABLES:
            if base_segment == "今天":
                return "today", "today_text", None
            if base_segment == "现在":
                return "now", "now_text", None
            return "clipboard", "clipboard", None

        if base_segment.startswith("输入:"):
            label = base_segment[3:].strip()
            if not label:
                raise TemplateRenderError("输入变量写法不正确，请使用例如 {{输入:项目名}} 的形式。")
            field = input_registry.get(label)
            if not field:
                field = TemplateInputField(
                    key=f"input_{len(input_registry)}",
                    label=label,
                    default="",
                )
                input_registry[label] = field
            return "input", field.key, field

        raise TemplateRenderError("未识别模板变量。")

    def _parse_filter_segment(self, filter_segment):
        if ":" not in filter_segment:
            return filter_segment.strip(), None

        filter_name, raw_arg = filter_segment.split(":", 1)
        filter_name = filter_name.strip()
        raw_arg = raw_arg.strip()
        if not filter_name:
            raise TemplateRenderError("过滤器写法不正确。")
        return filter_name, self._normalize_filter_arg(raw_arg)

    def _normalize_filter_arg(self, raw_arg):
        if not raw_arg:
            return ""
        if len(raw_arg) >= 2 and raw_arg[0] == raw_arg[-1] and raw_arg[0] in {"'", '"'}:
            return raw_arg[1:-1]
        return raw_arg

    def _filter_default(self, value, default_value=""):
        if value is None:
            return default_value
        if isinstance(value, str) and value == "":
            return default_value
        return value

    def _filter_format(self, value, format_string):
        if isinstance(value, (date, datetime)):
            return value.strftime(format_string)
        raise TemplateRenderError("“格式化”只能用于 {{今天}} 或 {{现在}}。")

    def _filter_upper(self, value):
        return str(value).upper()

    def _filter_lower(self, value):
        return str(value).lower()

    def _filter_trim(self, value):
        return str(value).strip()
